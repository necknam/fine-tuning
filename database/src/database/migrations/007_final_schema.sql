CREATE FUNCTION public.synchronize_step_completion() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.is_completed THEN NEW.completed_at:=coalesce(NEW.completed_at,now()); ELSE NEW.completed_at:=NULL; END IF;
 RETURN NEW;
END $$;
