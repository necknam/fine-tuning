CREATE VIEW public.roadmap_progress AS SELECT m.roadmap_id,count(s.step_id) AS total_steps,
 count(s.step_id) FILTER(WHERE s.is_completed) AS completed_steps,
 CASE WHEN count(s.step_id)=0 THEN 0 ELSE round(100.0*count(s.step_id) FILTER(WHERE s.is_completed)/count(s.step_id),2) END AS progress_percent
 FROM public.roadmaps m LEFT JOIN public.roadmap_steps s USING(roadmap_id) GROUP BY m.roadmap_id;

